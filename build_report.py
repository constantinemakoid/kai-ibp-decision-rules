def fixed_table(report):
    orig = report.table

    def table(headers, rows, widths_cm=None, caption=None, size=11, keep=True):
        rows = [tuple(str(v).replace("_", "_​") for v in row) for row in rows]
        t = orig(headers, rows, widths_cm, caption, size)
        mar = OxmlElement("w:tblCellMar")
        for side in ("left", "right"):
            el = OxmlElement(f"w:{side}")
            el.set(qn("w:w"), str(int(Cm(0.1).twips)))
            el.set(qn("w:type"), "dxa")
            mar.append(el)
        t._tbl.tblPr.append(mar)
        for row in t.rows:
            cs = OxmlElement("w:cantSplit")
            cs.set(qn("w:val"), "true")
            row._tr.get_or_add_trPr().insert(0, cs)
        if widths_cm:
            tblPr = t._tbl.tblPr
            lay = OxmlElement("w:tblLayout")
            lay.set(qn("w:type"), "fixed")
            tblPr.append(lay)
            grid = t._tbl.tblGrid
            for gc, w in zip(grid.findall(qn("w:gridCol")), widths_cm):
                gc.set(qn("w:w"), str(int(Cm(w).twips)))
            for row in t.rows:
                for c, w in zip(row.cells, widths_cm):
                    c.width = Cm(w)
        for row in t.rows[1:]:
            for c in row.cells:
                for par in c.paragraphs:
                    par.alignment = WD_ALIGN_PARAGRAPH.LEFT
        if keep == "head":
            for c in t.rows[0].cells:
                for par in c.paragraphs:
                    par.paragraph_format.keep_with_next = True
        elif keep and len(t.rows) <= 11:
            for row in t.rows[:-1]:
                for c in row.cells:
                    for par in c.paragraphs:
                        par.paragraph_format.keep_with_next = True
        return t
    report.table = table


def num(x, d=2):
    q = Decimal(repr(x)).quantize(Decimal(1).scaleb(-d), rounding=ROUND_HALF_UP)
    return f"{q:.{d}f}".replace(".", ",")


def plural(n, forms):
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return f"{n} {forms[0]}"
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return f"{n} {forms[1]}"
    return f"{n} {forms[2]}"


