def code(report, text, size=8.5):
    start = len(report.doc.paragraphs)
    report.code(text, size=size)
    for par in report.doc.paragraphs[start:]:
        par.paragraph_format.line_spacing = Pt(size + 1.2)
        par.paragraph_format.space_before = Pt(0)


def section(report, landscape):
    sec = report.doc.sections[-1]
    new = report.doc.add_section()
    w, h = sec.page_width, sec.page_height
    if landscape != (w > h):
        new.page_width, new.page_height = h, w
    new.orientation = WD_ORIENT.LANDSCAPE if landscape else WD_ORIENT.PORTRAIT
    new.left_margin, new.right_margin = sec.left_margin, sec.right_margin
    new.top_margin, new.bottom_margin = sec.top_margin, sec.bottom_margin
    if landscape:
        new.left_margin, new.right_margin, new.top_margin, new.bottom_margin = (
            sec.top_margin, sec.bottom_margin, Cm(1.5), Cm(1.5))
    else:
        first = report.doc.sections[0]
        new.left_margin, new.right_margin = first.left_margin, first.right_margin
        new.top_margin, new.bottom_margin = first.top_margin, first.bottom_margin
    new.different_first_page_header_footer = False


def yn(v):
    return "так" if v else "ні"


def page_numbers(report):
    sec = report.doc.sections[0]
    sec.different_first_page_header_footer = True
    par = sec.footer.paragraphs[0]
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.paragraph_format.first_line_indent = Cm(0)
    run = par.add_run()
    run.font.size = Pt(12)
    for kind, text in (("begin", None), (None, "PAGE"), ("end", None)):
        if kind:
            el = OxmlElement("w:fldChar")
            el.set(qn("w:fldCharType"), kind)
        else:
            el = OxmlElement("w:instrText")
            el.set(qn("xml:space"), "preserve")
            el.text = text
        run._r.append(el)


